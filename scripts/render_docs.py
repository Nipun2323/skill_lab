"""Render docs/LLD.md and docs/EVALUATION.md from templates, filling every figure from
docs/evaluation_results.json, so no accuracy number in the docs is typed by hand.

Placeholders:  {{pct:path}} -> 31.0%    {{pct2:path}} -> 31.02%   {{num3:path}} -> 0.267
               {{int:path}} -> 42,657   {{raw:path}}  -> value as-is
               {{pt:pathA-pathB}} -> difference in percentage points, e.g. 6.1
Paths are dotted keys into the JSON, e.g. methods.full.top3.

Usage:  python scripts/render_docs.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
TEMPLATES = DOCS / "templates"
PLACEHOLDER = re.compile(r"\{\{(\w+):([^}]+)\}\}")


def lookup(data: dict, path: str):
    node = data
    for part in path.strip().split("."):
        node = node[part]
    return node


def render(text: str, data: dict) -> str:
    def sub(m: re.Match) -> str:
        kind, path = m.group(1), m.group(2)
        if kind == "pt":
            a, b = path.split("-")
            return f"{(lookup(data, a) - lookup(data, b)) * 100:.1f}"
        value = lookup(data, path)
        if kind == "pct":
            return f"{value * 100:.1f}%"
        if kind == "pct2":
            return f"{value * 100:.2f}%"
        if kind == "num3":
            return f"{value:.3f}"
        if kind == "int":
            return f"{value:,}"
        if kind == "raw":
            return str(value)
        raise ValueError(f"unknown placeholder kind: {kind}")
    out = PLACEHOLDER.sub(sub, text)
    leftover = re.findall(r"\{\{[^}]*\}\}", out)
    if leftover:
        raise ValueError(f"unrendered placeholders: {leftover[:3]}")
    return out


def main(argv: list[str] | None = None) -> int:
    results_path = DOCS / "evaluation_results.json"
    if not results_path.is_file():
        print("docs/evaluation_results.json not found; run scripts/evaluate.py first.", file=sys.stderr)
        return 2
    data = json.loads(results_path.read_text(encoding="utf-8"))
    for name in ("LLD.md", "EVALUATION.md"):
        tmpl = (TEMPLATES / f"{name}.tmpl").read_text(encoding="utf-8")
        header = ("<!-- Generated by scripts/render_docs.py from docs/templates/"
                  f"{name}.tmpl and docs/evaluation_results.json. Edit the template, not this file. -->\n\n")
        (DOCS / name).write_text(header + render(tmpl, data), encoding="utf-8")
        print(f"Wrote docs/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
